//! The derives allow references to a `#[deprecated]` wrapper or field in generated code.
//! They also carry over `allow` and `expect` for `deprecated` and `warnings` from the wrapper
//! or field as `allow`, preserving the lint name.

mod from;
mod id;
mod into;
mod newtype;

use proc_macro::TokenStream;
use proc_macro2::Span;
use quote::quote;
use syn::DeriveInput;
use syn::Ident;
use syn::Type;

/// Implements `From<Inner>` for a non-generic, single-field tuple struct.
///
/// Use this derive when every inner value is valid without further validation or normalization.
#[proc_macro_derive(From)]
pub fn derive_from(input: TokenStream) -> TokenStream {
    derive_newtype(input, "From", from::expand)
}

/// Implements `From<Wrapper>` for the inner type of a non-generic, single-field tuple struct.
///
/// The wrapper can then be consumed with `.into()` while retaining its own construction rules.
///
/// ```
/// use macros::Into;
///
/// #[derive(Into)]
/// struct NonEmptyText(String);
///
/// let text: String = NonEmptyText("hello".to_owned()).into();
/// assert_eq!(text, "hello");
/// ```
///
/// ```compile_fail,E0277
/// use macros::Into;
///
/// #[derive(Into)]
/// struct NonEmptyText(String);
///
/// let _: NonEmptyText = String::new().into();
/// ```
#[proc_macro_derive(Into)]
pub fn derive_into(input: TokenStream) -> TokenStream {
    derive_newtype(input, "Into", into::expand)
}

/// Includes the conversions generated by `#[derive(From, Into)]` and delegates `FromStr` and
/// `Display` to the inner type. Combining `Id` with either conversion derive generates duplicate
/// implementations.
#[proc_macro_derive(Id)]
pub fn derive_id(input: TokenStream) -> TokenStream {
    derive_newtype(input, "Id", id::expand)
}

fn derive_newtype(
    input: TokenStream,
    derive_name: &str,
    expand: fn(&Ident, &Type) -> proc_macro2::TokenStream,
) -> TokenStream {
    let input = syn::parse_macro_input!(input as DeriveInput);

    let field = match newtype::field(&input, derive_name) {
        Ok(field) => field,
        Err(error) => return error.into_compile_error().into(),
    };
    let attrs = input.attrs.iter().chain(&field.attrs);
    // Preserve the warnings group so an enclosing `forbid(deprecated)` still applies.
    let allowed_lints = ["deprecated", "warnings"]
        .into_iter()
        .filter(|lint| attrs.clone().any(|attr| newtype::permits_lint(attr, lint)))
        .map(|lint| Ident::new(lint, Span::call_site()));
    let impls = expand(&input.ident, &field.ty);
    quote! {
        #(#[allow(#allowed_lints, reason = "The generated impls use the declared wrapper and field.")])*
        const _: () = { #impls };
    }
    .into()
}
